-- Day 2: the assistant's window on the data (migration 005_analytics_layer).
-- Schema `analytics` = certified, read-only views + data_trust. Role assistant_ro may read ONLY this schema
-- (plus kb_chunks/match_kb for RAG). Raw facts and the `ops` schema are not granted.

create schema if not exists analytics;

create view analytics.kpi_monthly    as select * from cottonil.mv_kpi_monthly;
create view analytics.kpi_yearly     as select * from cottonil.mv_kpi_yearly;
create view analytics.category_year  as select * from cottonil.mv_category_year;
create view analytics.discount_band  as select * from cottonil.mv_discount_band;
create view analytics.seasonality    as select * from cottonil.mv_seasonality;

-- customers without names (the assistant answers about segments, not individuals)
create view analytics.customer_rfm as
select customer_id, governorate_ar, customer_segment, age_band, joined_date, first_order, last_order,
       orders, net_egp, aov_egp, recency_days, fav_category, r_score, f_score, m_score, dormant, value_tier
from cottonil.mv_customer_rfm;

-- channel x year (order label only; see trust rule on sales_channel)
create materialized view cottonil.mv_channel_year as
select extract(year from o.order_date)::int yr, o.sales_channel, count(*) orders, sum(o.net_before_tax_egp) net_egp,
       round(avg(o.net_before_tax_egp), 2) aov_egp
from cottonil.fact_order o group by 1, 2;
create view analytics.channel_year as select * from cottonil.mv_channel_year;

-- product totals FULL window
create materialized view cottonil.mv_product as
select p.product_id, p.product_name_ar, p.category_en, sum(l.quantity) units, sum(l.net_line_egp) net_egp,
       sum(l.margin_egp) margin_egp, round(100 * sum(l.margin_egp) / sum(l.net_line_egp), 2) gm_pct
from cottonil.fact_order_line l join cottonil.dim_product p using (product_id) group by 1, 2, 3;
create view analytics.product_totals as select * from cottonil.mv_product;

-- returns summary by year (refunds are usable; reasons are uniform, see trust rule)
create materialized view cottonil.mv_returns_year as
select extract(year from return_date)::int yr, count(*) returns, sum(return_quantity) units_returned,
       sum(refund_amount_egp) refund_egp
from cottonil.fact_return group by 1;
create view analytics.returns_year as select * from cottonil.mv_returns_year;

-- ---------------------------------------------------------------- data trust register
create table analytics.data_trust (
  topic           text primary key,
  source_tables   text not null,
  status          text not null check (status in ('usable', 'usable_with_caveat', 'not_usable')),
  safe_to_say     text not null,
  cannot_answer   text,
  reason          text not null
);

